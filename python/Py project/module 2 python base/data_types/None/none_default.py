def calculate_discount(price, discount=None):
    # Если скидка не указана (None), устанавливаем дефолтное значение 5% (0.05)
    if discount is None:
        discount = 0.05
    
    # Вычисляем итоговую цену
    final_price = price * (1 - discount)
    return final_price

# --- Тестирование ---
print("--- Задача 1: Скидки ---")
# Вызов без указания скидки (сработает значение по умолчанию 0.05)
print(f"Цена 100 без указания скидки: {calculate_discount(100)}")  # Ожидается: 95.0

# Вызов с явным указанием скидки 20% (0.2)
print(f"Цена 100 со скидкой 20%: {calculate_discount(100, 0.2)}")  # Ожидается: 80.0

def add_to_list(item, my_list=None):
    # Если список не передан, создаем новый пустой список
    if my_list is None:
        my_list = []
    
    # Добавляем элемент
    my_list.append(item)
    return my_list

# --- Тестирование ---
print("\n--- Задача 2: Списки ---")
# 1. Вызов без списка (создается новый)
result1 = add_to_list("яблоко")
print(f"Вызов 1 (без списка): {result1}")  # Ожидается: ['яблоко']

# 2. Повторный вызов без списка (должен создать НОВЫЙ список, а не добавить к старому!)
result2 = add_to_list("банан")
print(f"Вызов 2 (без списка): {result2}")  # Ожидается: ['банан']

# 3. Вызов с существующим списком
existing_list = ["груша", "слива"]
result3 = add_to_list("апельсин", existing_list)
print(f"Вызов 3 (с существующим списком): {result3}")  # Ожидается: ['груша', 'слива', 'апельсин']

def send_email(subject, body, recipient=None):
    # Если получатель не указан, используем адрес поддержки по умолчанию
    if recipient is None:
        recipient = "support@example.com"
    
    # Выводим красиво отформатированное сообщение
    print(f"📩 Тема: {subject}")
    print(f"📝 Тело письма: {body}")
    print(f"👤 Получатель: {recipient}")
    print("-" * 40)

# --- Тестирование ---
print("--- Задача 3: Отправка email ---")
# 1. Вызов без указания получателя (сработает дефолтное значение)
send_email("Ошибка входа", "Не могу войти в личный кабинет, помогите!")

# 2. Вызов с явным указанием получателя
send_email("Отчет за месяц", "Все задачи выполнены в срок.", "boss@company.com")